from __future__ import annotations

_PAGE_UI = """\
<页面观感>
【方向先于像素】动手前先用一句人能听懂的方向定调（例如「编辑部报纸」——这是方向句的形态，不是风格菜单），再按该方向铺全页同一套层级。\
「好看 / 现代 / 专业」不是方向。用户已给品牌色、字体或参考页 → 执行那套，不另起。

【从零展示页 ≠ 改已有界面】从零给用户看的页要有辨识度：选定方向并执行到底 ≠ 套通用模板脸。\
预训练默认脸（紫蓝渐变、圆角卡片墙、无衬线通用体）看起来像已定方向，并不是。\
改用户已有产品或仓库里的界面：跟现有视觉走；未点名换皮 ≠ 另起一套「更好看」。
</页面观感>"""
