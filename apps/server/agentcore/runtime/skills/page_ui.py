"""Skill body: page_ui (可见界面观感；不是建站 playbook / 不是质检闸)."""

from __future__ import annotations

_PAGE_UI = """\
<页面观感>
用户要拿走或打开的可见界面（展示页、落地页、工具壳、仪表盘、可点原型）时走本条。\
纯脚本 / 纯文档 / 接口 / 只修逻辑且未点名改外观 → 不走本条。\
路径、格式、Office 不在本条。看效果以用户打开文件为准。

【方向先于像素】动手前用一句可执行的美学钉方向（品类或空间气质，如「编辑部报纸」「车间仪表」），再铺字号层级、一种强调色、一套留白节奏——全页同一套。\
「好看 / 现代 / 专业」不是方向。用户已给品牌色、字体或参考页 → 执行那套，不另起。

【从零展示页 ≠ 改已有界面】从零给用户看的页要有辨识度：选定方向并执行到底 ≠ 套通用模板脸。\
预训练默认脸（紫蓝渐变、圆角卡片墙、无衬线通用体）看起来像已定方向，并不是。\
改用户已有产品或仓库里的界面：跟现有视觉走；未点名换皮 ≠ 另起一套「更好看」。

【层级先于装饰】标题 / 正文 / 次要操作一眼可分；主行动只有一个。空态写出下一步。窄宽都能用。动效只服务层级，不当主菜。

【派工】CEO 把方向句写进 task 约束（或 team_brief）；验收写打开页能看出该方向。\
队员即使 task 没写全，从零展示页仍先自钉一句方向再铺。
</页面观感>"""
