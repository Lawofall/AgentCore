from __future__ import annotations

_DATA_FILE_LANDING = """\
<data_file_landing>
## 数据文件 → 可打开产物

用户丢账单 / 报表 / 导出记录 / 凭证等数据文件（PDF、CSV、xlsx、HTML 表、文本导出）+ 一句话，\
要一份能直接打开的整理产物时走本页：【单 worker 线性】一人做完。套多角色 DAG / 为拆表另开流水线 ≠ 本页。

【有执行】对照 `<workspace_context>`。`code_execute=已装配`：CEO 派 `form=files`，\
`artifacts` 写死产物路径，task 点源文件。

**原件为真源**：看原件——读工作区原文件。PDF/Office 预解析 `.md` / `file_read` 抽出文本只是线索 ≠ 表结构真源。\
xlsx/csv 须 `code_execute` 按相对路径读 ≠ 指望 `file_read` 抽全表。\
PDF 在执行环境用已预装库自己抽：有框线格子表用抽表专用库（按页抽文本会拆行）；\
文本流排版以文本层为真值，抽表空表 ≠ 失败。对着预解析残文硬凑 ≠ 换抽取。\
已预装库以本回合 `code_execute` 工具描述为准，勿另猜库名。

**认形态**：原件真实结构（列对齐、分页页眉、合并格、分隔符、编码）。\
预解析把一行拆成多行、页眉混进数据、列对不齐 → 换抽取（执行环境重抽；文本流改抽文本层）≠ 顺着预解析拆乱文本继续。

**变换用脚本不手抄**：按认清的形态抽，再按用户口径变换（分表 / 分栏 / 汇总）。\
写一次性变换脚本，落盘后用 `code_execute` 跑 ≠ 模型逐行手抄 CSV / 单元格进 `file_write`。\
抽取仍乱 → 改脚本再跑 ≠ 退回手抄。

**不变量校验不过闸不交**：分类笔数之和 = 源记录总数；有金额则核对合计；抽样几行对照原件。\
用脚本算 ≠ 心算凑。失败则修变换再跑 ≠ 改口径数字去凑、≠ 无校验交差。

**产出可打开文件**：真目标后缀写入工作区（有执行且 `.xlsx=可产` → 交真 `.xlsx`）。\
handoff 指向该路径，用户能直接打开 / 预览。只交脚本或说明 ≠ 已可打开的表。\
交表时同时满足下方【表格产物·质量基线】。

【表格产物·质量基线】凡本回合交付物是「可打开的表」（xlsx / 同类电子表格；csv/tsv 只落实该格式能表达的部分）都适用——\
与数据来自哪、用户怎么称呼无关，不是某一行业或某一数据源的专用模板。无执行三件套不是表，本条不适用。
1. **明细与汇总分开**：全量明细是一张（或一组）表，汇总/统计是另一张（或另一块）。\
逐行明细和分类小计揉进同一张无结构的表 ≠ 本条。
2. **单元格用对的类型**：日期列写成日期类型，不要用看起来像日期的文本；\
可加总的数值列写成数值，并套千分位或该列惯用数字格式，不要把数字当字符串。文本列才用文本。
3. **表头可停留、可筛选**：格式支持时冻结表头行、打开筛选。纯文本表做不到就跳过这两项，其余仍做。
4. **每张明细带合计**：每张明细表在数据末行给可加总列合计（或条数，按列语义）。\
只在对话或 handoff 里报一个总数 ≠ 本条。
5. **口径写进表里**：分类 / 分组 / 筛选规则须写在产物内（独立口径表，或汇总旁的说明区），\
打开文件就能看见「按什么规则分的」。只写在对话或 handoff ≠ 本条。

【派工结构】CEO 派交表：`form=files`，`artifacts` 写死表路径；把上列基线写进 task 或 team_brief。\
队员交表时即使 task 没写全，仍按本基线做。

【口径】用户只给粗分法时，可自决更合理的细类（例如把退款从收支里拆出），把规则写进产物汇总页。\
末尾给改口入口（再说一声即可重跑脚本）。拿交付当人质 ≠ 本条——先交文件，再谈口径。

【无执行】`code_execute=未装配`：本回合的完整交付不是表格，而是三件套——凑齐即正常完成，不是缺口。\
CEO 派 `form=files`，`artifacts` 写死下面两份路径，task 点源文件：
1. **原件结构报告**（落盘）：只写本回合已经给出的事实。表格类附件用结构面（列名、总行数、每列推断类型、样例行）；\
PDF/抽出文本只写抽出里能看见的形态（分页、拆行、列对不齐也照实写）。凭空补列、补行、补金额 ≠ 本条。
2. **待跑变换脚本**（落盘）：按认清的形态写好一次性脚本，读工作区原件、按用户口径变换、做不变量校验；本回合不跑。\
把抽出文本或样例逐行手抄进 csv/xlsx 交差 ≠ 本条。
3. **一句人话下一步**（正文与 handoff.next_steps）：运算环境暂时不可用，稍后再试即可。\
让用户绑本机文件夹、改工作区形态、导入到云、在本机终端跑脚本 ≠ 本条。
`.xlsx=不可产` 时不要改手抄 csv 顶替表格。谎称已生成 / 已校验 ≠ 本条。
</data_file_landing>"""
